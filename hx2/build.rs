// Embeds the built web UI (ui/dist) into the binary, the way
// scripts/gen-ui-assets.ts embeds it into the TypeScript client: one entry per
// file, keyed by its URL path. `hx ui` serves the React app as built, so the
// hx2 build runs `bun run build` in ui/ first (.github/workflows/differential.yml).
// Without ui/dist the table is empty and `hx2 ui` falls back to serving the
// source checkout's ui/dist from disk, as the TypeScript client does.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let entries = match fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let p = entry.path();
        match entry.file_type() {
            Ok(t) if t.is_dir() => walk(&p, out),
            Ok(t) if t.is_file() => out.push(p),
            _ => {}
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dist = manifest.join("..").join("ui").join("dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    println!("cargo:rerun-if-changed=build.rs");
    let mut files: Vec<PathBuf> = Vec::new();
    if dist.join("index.html").is_file() {
        walk(&dist, &mut files);
    } else {
        println!("cargo:warning=ui/dist/index.html not found: this build carries no web UI (run `bun run build` in ui/ first)");
    }
    files.sort();
    let mut src = String::from("// Generated by build.rs from ui/dist.\npub static UI_ASSETS: &[(&str, &[u8])] = &[\n");
    for f in &files {
        let rel = f.strip_prefix(&dist).expect("under dist").to_string_lossy().replace('\\', "/");
        let url = if rel.starts_with('/') { rel } else { format!("/{}", rel) };
        let abs = fs::canonicalize(f).unwrap_or_else(|_| f.clone());
        src.push_str(&format!("    ({:?}, include_bytes!({:?})),\n", url, abs.to_string_lossy()));
    }
    src.push_str("];\n");
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("ui_assets.rs");
    fs::write(out, src).expect("write ui_assets.rs");
}
